async def seed_database(session: AsyncSession, force: bool = False) -> int:
    """
    Populate database with rich starter notes.
    If force is True, clears and re-inserts all seed notes.
    If database has fewer notes than SEED_NOTES, supplements missing seed notes.
    Returns the count of notes inserted.
    """
    if force:
        await session.execute(delete(Note))
        await session.commit()

    count_stmt = select(func.count(Note.id))
    res = await session.execute(count_stmt)
    existing_count = res.scalar() or 0

    if not force and existing_count >= len(SEED_NOTES):
        return 0

    existing_texts_stmt = select(Note.text)
    existing_texts_res = await session.execute(existing_texts_stmt)
    existing_texts = set(existing_texts_res.scalars().all())

    inserted = 0
    for item in SEED_NOTES:
        if item["text"] in existing_texts:
            continue
        tags = item.get("tags") or extract_tags(item["text"])
        note = Note(
            text=item["text"],
            tags=tags,
            status=item.get("status", "published")
        )
        session.add(note)
        inserted += 1

    if inserted > 0:
        await session.commit()
    return inserted


async def main():
    import sys
    force = "--force" in sys.argv or "-f" in sys.argv
    print(f"🌱 Starting database seeding (force={force})...")
    async with async_session_factory() as session:
        count = await seed_database(session, force=force)
        print(f"✅ Seeded {count} notes. Total in seed dataset: {len(SEED_NOTES)}")


if __name__ == "__main__":
    asyncio.run(main())
